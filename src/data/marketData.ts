import { StockQuote, Candle } from '../types';

function generateHistoricalCandles(
  endPrice: number,
  volatilityPct: number,
  seed: number,
  count: number = 65
): Candle[] {
  const candles: Candle[] = [];
  const prices: number[] = [endPrice];
  let s = seed;
  const nextRand = () => {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };

  // Walk backward from endPrice to create realistic historical trajectory
  let cursor = endPrice;
  for (let i = 1; i < count; i++) {
    const drift = (nextRand() - 0.52) * volatilityPct;
    cursor = Math.max(20, Math.round(cursor / (1 + drift) * 100) / 100);
    prices.unshift(cursor);
  }

  const now = Date.now();
  const dayMs = 24 * 60 * 60 * 1000;

  for (let i = 0; i < count; i++) {
    const close = prices[i];
    const open = i === 0 ? Math.round(close * (1 - (nextRand() - 0.5) * volatilityPct) * 100) / 100 : prices[i - 1];
    const spread = Math.max(open, close) * (volatilityPct * (0.4 + nextRand() * 0.8));
    const high = Math.round((Math.max(open, close) + spread * 0.6) * 100) / 100;
    const low = Math.round(Math.max(1, Math.min(open, close) - spread * 0.6) * 100) / 100;
    const timestamp = now - (count - 1 - i) * dayMs;
    const d = new Date(timestamp);
    const time = d.toLocaleDateString('en-IN', { day: '2-digit', month: 'short' });
    const volume = Math.floor(850000 + nextRand() * 4200000);

    candles.push({
      time,
      timestamp,
      open,
      high,
      low,
      close,
      volume,
    });
  }

  return candles;
}

