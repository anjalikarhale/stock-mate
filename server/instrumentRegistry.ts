const BY_SYMBOL = new Map<string, RegisteredInstrument>();
const BY_EXCHANGE_SYMBOL = new Map<string, RegisteredInstrument>();

for (const inst of INSTRUMENT_REGISTRY) {
  BY_SYMBOL.set(inst.symbol.toUpperCase(), inst);
  BY_EXCHANGE_SYMBOL.set(inst.growwExchangeSymbol.toUpperCase(), inst);
}

// Common aliases
BY_SYMBOL.set('NIFTY50', BY_SYMBOL.get('NIFTY')!);
BY_SYMBOL.set('NIFTY 50', BY_SYMBOL.get('NIFTY')!);
BY_SYMBOL.set('NIFTY BANK', BY_SYMBOL.get('BANKNIFTY')!);

export function getRegisteredInstrument(symbol: string): RegisteredInstrument | undefined {
  if (!symbol) return undefined;
  return BY_SYMBOL.get(symbol.trim().toUpperCase());
}

export function getInstrumentByExchangeSymbol(exchangeSymbol: string): RegisteredInstrument | undefined {
  if (!exchangeSymbol) return undefined;
  return BY_EXCHANGE_SYMBOL.get(exchangeSymbol.trim().toUpperCase());
}

export function getAllRegisteredInstruments(kind?: InstrumentKind): RegisteredInstrument[] {
  if (!kind) return INSTRUMENT_REGISTRY;
  return INSTRUMENT_REGISTRY.filter((i) => i.instrumentType === kind);
}

export function isValidExchangeSymbolFormat(exchangeSymbol: string): boolean {
  return /^(NSE|BSE)_[A-Z0-9&-]{1,30}$/.test(exchangeSymbol.trim());
}
